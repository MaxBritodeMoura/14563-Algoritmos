# Exercício 8 
# # Crie um programa que peça ao usuário que digite 4 notas de uma disciplina. Calcule e exiba a 
# # média das notas.  

nota1=float(input("Digite a 1 notas de uma disciplina de um aluno: "))
nota2=float(input("Digite a 2 notas de uma disciplina de um aluno: "))
nota3=float(input("Digite a 3 notas de uma disciplina de um aluno: "))
nota4=float(input("Digite a 4 notas de uma disciplina de um aluno: "))

media=(nota1+nota2+nota3+nota4)/4
print(round(media,2))

